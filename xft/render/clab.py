"""Render the containerlab topology from intent/topology.yml.

Containerlab only needs a third of each link row — the two router:interface
ends. The subnet and OSPF area in the same row feed the router configs later.
Generating both from one table is what keeps a cable from pointing at an
interface no config knows about.

    python -m xft.render.clab          # write lab/xft.clab.yaml
    python -m xft.render.clab --check  # fail if the file is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
INTENT = REPO / "intent" / "topology.yml"
OUTPUT = REPO / "lab" / "xft.clab.yaml"

HEADER = (
    "# GENERATED by xft.render.clab from intent/topology.yml — do not hand-edit.\n"
    "# Change the intent file and re-run: python -m xft.render.clab\n"
)


def load_intent(path: Path = INTENT) -> dict:
    with path.open() as fh:
        return yaml.safe_load(fh)


def check_interfaces(intent: dict) -> list[str]:
    """Catch the transcription error that silently breaks a topology: the same
    router:interface used by two links, or a link naming an unknown router."""
    known = {r["name"] for r in intent["routers"]}
    seen: dict[tuple[str, str], int] = {}
    problems = []

    for link in intent["links"]:
        for end in ("source", "destination"):
            router, iface = link[end]["router"], link[end]["interface"]
            if router not in known:
                problems.append(f"link {link['id']}: unknown router {router!r}")
            port = (router, iface)
            if port in seen:
                problems.append(
                    f"link {link['id']}: {router}:{iface} already used by link {seen[port]}"
                )
            else:
                seen[port] = link["id"]
    return problems


def build(intent: dict) -> dict:
    defaults = intent["defaults"]
    daemons = defaults["daemons_file"]

    nodes = {
        router["name"]: {"binds": [f"{daemons}:/etc/frr/daemons"]}
        for router in intent["routers"]
    }
    links = [
        {
            "endpoints": [
                f"{link['source']['router']}:{link['source']['interface']}",
                f"{link['destination']['router']}:{link['destination']['interface']}",
            ]
        }
        for link in intent["links"]
    ]

    return {
        "name": intent["meta"]["name"],
        "topology": {
            "defaults": {"kind": "linux"},
            "kinds": {
                "linux": {
                    "image": defaults["image"],
                    "exec": ["sysctl -w net.ipv4.ip_forward=1"],
                }
            },
            "nodes": nodes,
            "links": links,
        },
    }


def render(intent: dict) -> str:
    return HEADER + yaml.safe_dump(build(intent), sort_keys=False, width=100)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit non-zero if the generated file is out of date",
    )
    args = parser.parse_args(argv)

    intent = load_intent()

    problems = check_interfaces(intent)
    if problems:
        for problem in problems:
            print(f"error: {problem}", file=sys.stderr)
        return 1

    rendered = render(intent)

    if args.check:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != rendered:
            print(f"error: {OUTPUT.name} is stale; re-run without --check", file=sys.stderr)
            return 1
        print(f"{OUTPUT.name} is up to date")
        return 0

    OUTPUT.write_text(rendered)
    print(
        f"wrote {OUTPUT.relative_to(REPO)}: "
        f"{len(intent['routers'])} nodes, {len(intent['links'])} links"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
